impl ReceiptOutcome {
    /// The `notify` keyword a sender must have asked for to get this receipt.
    #[must_use]
    pub const fn notify_class(self) -> NotifyClass {
        match self {
            Self::Delivered => NotifyClass::Success,
            Self::Delayed => NotifyClass::Delay,
            _ => NotifyClass::Failure,
        }
    }
}

/// One `notify` keyword (RFC 3461 `NOTIFY`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum NotifyClass {
    /// No receipt at all. Only valid alone.
    Never,
    /// Expiry and other failures.
    Failure,
    /// The "not popped yet" alert.
    Delay,
    /// The message was popped.
    Success,
}

/// Which receipts a sender asked for. Stored as a canonical comma list
/// (`never`, or any of `failure`, `delay`, `success` in that order).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct NotifyOn {
    /// Receipt on expiry or another failure.
    pub failure: bool,
    /// Receipt when the alert fires.
    pub delay: bool,
    /// Receipt when the message is popped.
    pub success: bool,
}

impl NotifyOn {
    /// No receipts. Receipts themselves and legacy rows use it.
    pub const NEVER: Self = Self {
        failure: false,
        delay: false,
        success: false,
    };

    /// The default for a new message: `failure,delay`.
    pub const DEFAULT: Self = Self {
        failure: true,
        delay: true,
        success: false,
    };

    /// Build from the keywords a caller sent. `never` must be alone, the list
    /// must not be empty and a keyword may not repeat.
    ///
    /// # Errors
    /// Returns [`crate::MemoryError::InvalidInput`] on an empty list, a
    /// repeated keyword or `never` combined with another keyword.
    pub fn from_classes(classes: &[NotifyClass]) -> crate::MemoryResult<Self> {
        if classes.is_empty() {
            return Err(crate::MemoryError::InvalidInput(
                "notify must name at least one of never, failure, delay, success".into(),
            ));
        }
        let mut out = Self::NEVER;
        let mut never = false;
        for class in classes {
            let slot = match class {
                NotifyClass::Never => &mut never,
                NotifyClass::Failure => &mut out.failure,
                NotifyClass::Delay => &mut out.delay,
                NotifyClass::Success => &mut out.success,
            };
            if *slot {
                return Err(crate::MemoryError::InvalidInput(
                    "notify must not repeat a keyword".into(),
                ));
            }
            *slot = true;
        }
        if never && out != Self::NEVER {
            return Err(crate::MemoryError::InvalidInput(
                "notify \"never\" cannot be combined with another keyword".into(),
            ));
        }
        Ok(out)
    }

    /// Whether this asks for a receipt of `class`.
    #[must_use]
    pub const fn wants(self, class: NotifyClass) -> bool {
        match class {
            NotifyClass::Never => false,
            NotifyClass::Failure => self.failure,
            NotifyClass::Delay => self.delay,
            NotifyClass::Success => self.success,
        }
    }

    /// Canonical storage string.
    #[must_use]
    pub fn as_canonical(self) -> String {
        let parts: Vec<&str> = [
            (self.failure, "failure"),
            (self.delay, "delay"),
            (self.success, "success"),
        ]
        .into_iter()
        .filter_map(|(on, name)| on.then_some(name))
        .collect();
        if parts.is_empty() {
            "never".to_owned()
        } else {
            parts.join(",")
        }
    }
}

impl std::str::FromStr for NotifyOn {
    type Err = crate::MemoryError;

    /// Parse the canonical storage string written by [`Self::as_canonical`].
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let classes = s
            .split(',')
            .map(|part| match part {
                "never" => Ok(NotifyClass::Never),
                "failure" => Ok(NotifyClass::Failure),
                "delay" => Ok(NotifyClass::Delay),
                "success" => Ok(NotifyClass::Success),
                other => Err(crate::MemoryError::MalformedRecord(format!(
                    "unknown notify keyword: {other}"
                ))),
            })
            .collect::<Result<Vec<_>, _>>()?;
        let parsed = Self::from_classes(&classes)
            .map_err(|e| crate::MemoryError::MalformedRecord(e.to_string()))?;
        if parsed.as_canonical() != s {
            return Err(crate::MemoryError::MalformedRecord(format!(
                "notify is not in canonical form: {s}"
            )));
        }
        Ok(parsed)
    }
}

impl Serialize for NotifyOn {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(&self.as_canonical())
    }
}

impl<'de> Deserialize<'de> for NotifyOn {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let raw = String::deserialize(deserializer)?;
        raw.parse().map_err(serde::de::Error::custom)
    }
}

/// Smallest time to live a sender may ask for.
pub const MIN_MESSAGE_TTL_SECS: u64 = 60;
/// Largest time to live a sender may ask for. The server also never extends a
/// message past its priority's default (see [`DeliveryPolicy::deadlines`]).
pub const MAX_MESSAGE_TTL_SECS: u64 = 30 * 24 * 60 * 60;
/// How long a receipt waits in the sender's inbox before it expires.
pub const RECEIPT_TTL_SECS: u64 = 7 * 24 * 60 * 60;

/// Operator defaults for message deadlines (`[messaging]` in `config.toml`).
/// A `None` alert disables the "not popped yet" alert for that priority.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DeliveryPolicy {
    /// Time to live of a `low` message, in seconds.
    pub ttl_low_secs: u64,
    /// Time to live of a `normal` message, in seconds.
    pub ttl_normal_secs: u64,
    /// Time to live of a `high` message, in seconds.
    pub ttl_high_secs: u64,
    /// Alert delay for a `normal` message, in seconds.
    pub alert_normal_secs: Option<u64>,
    /// Alert delay for a `high` message, in seconds.
    pub alert_high_secs: Option<u64>,
}

impl Default for DeliveryPolicy {
    /// The design's defaults: `low` 7 days without alert, `normal` 3 days
    /// with an alert after 2 hours, `high` 24 hours with an alert after 15
    /// minutes.
    fn default() -> Self {
        Self {
            ttl_low_secs: 7 * 24 * 60 * 60,
            ttl_normal_secs: 3 * 24 * 60 * 60,
            ttl_high_secs: 24 * 60 * 60,
            alert_normal_secs: Some(2 * 60 * 60),
            alert_high_secs: Some(15 * 60),
        }
    }
}

/// Absolute deadlines stamped on a new message, in microseconds since the
/// epoch.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Deadlines {
    /// When the message expires.
    pub expires_at_us: i64,
    /// When the "not popped yet" alert fires, if ever. Always before
    /// `expires_at_us`.
    pub no_pop_alert_at_us: Option<i64>,
}

impl DeliveryPolicy {
    /// Default time to live for `priority`, in seconds.
    #[must_use]
    pub const fn ttl_secs(&self, priority: MessagePriority) -> u64 {
        match priority {
            MessagePriority::Low => self.ttl_low_secs,
            MessagePriority::Normal => self.ttl_normal_secs,
            MessagePriority::High => self.ttl_high_secs,
        }
    }

    /// Alert delay for `priority`, in seconds.
    #[must_use]
    pub const fn alert_secs(&self, priority: MessagePriority) -> Option<u64> {
        match priority {
            MessagePriority::Low => None,
            MessagePriority::Normal => self.alert_normal_secs,
            MessagePriority::High => self.alert_high_secs,
        }
    }

    /// Deadlines for a message created at `now_us`. A requested time to live
    /// can shorten the priority's default, never extend it. An alert that
    /// would fire at or after expiry is dropped. Arithmetic saturates, so no
    /// configuration can wrap a deadline into the past.
    #[must_use]
    pub fn deadlines(
        &self,
        priority: MessagePriority,
        requested_ttl_secs: Option<u64>,
        now_us: i64,
    ) -> Deadlines {
        let ttl = requested_ttl_secs.map_or(self.ttl_secs(priority), |requested| {
            requested.min(self.ttl_secs(priority))
        });
        let after = |secs: u64| {
            let micros = i64::try_from(secs.saturating_mul(1_000_000)).unwrap_or(i64::MAX);
            now_us.saturating_add(micros)
        };
        let expires_at_us = after(ttl);
        let no_pop_alert_at_us = self
            .alert_secs(priority)
            .map(after)
            .filter(|alert| *alert < expires_at_us);
        Deadlines {
            expires_at_us,
            no_pop_alert_at_us,
        }
    }
}

/// Delivery block of a message as its sender sees it.
#[derive(Debug, Clone, Serialize)]
pub struct MessageDelivery {
    /// What happened to the message.
    pub state: DeliveryState,
    /// Why, when there is a reason to give.
    pub reason: Option<DeliveryReason>,
    /// When the recipient's quota resets, when its harness stated it. Set
    /// only with `quota_exhausted`.
    pub retry_after: Option<Timestamp>,
    /// When the message expires if nobody pops it. `None` for mail sent
    /// before delivery states existed.
    pub expires_at: Option<Timestamp>,
    /// When the "not popped yet" alert will fire, until it has fired.
    pub no_pop_alert_at: Option<Timestamp>,
    /// Which receipts the sender asked for.
    pub notify: NotifyOn,
}

/// Schema tag of the structured receipt block.
pub const RECEIPT_SCHEMA: &str = "ai-memory.receipt/v1";

/// Structured part of a receipt. Every field is an id, an enumerated value or
/// a timestamp; the recipient coordinate is the receipt's own sender
/// coordinate.
#[derive(Debug, Clone, Serialize)]
pub struct DeliveryReceipt {
    /// Always [`RECEIPT_SCHEMA`].
    pub schema: &'static str,
    /// The message this receipt is about. `None` once that message is gone.
    pub receipt_for: Option<MessageId>,
    /// What happened.
    pub outcome: ReceiptOutcome,
    /// Why, when there is a reason to give.
    pub reason: Option<DeliveryReason>,
    /// When the server generated the receipt.
    pub at: Timestamp,
    /// When the recipient's quota resets, on a `quota_exhausted` receipt
    /// whose harness stated it.
    pub retry_after: Option<Timestamp>,
}

/// Subject of a receipt: `receipt: <outcome> <original id>`.
#[must_use]
pub fn receipt_subject(outcome: ReceiptOutcome, receipt_for: MessageId) -> String {
    format!("receipt: {} {receipt_for}", outcome.as_str())
}

/// Body of a receipt, rendered from enumerated values and ids only.
#[must_use]
pub fn receipt_body(
    outcome: ReceiptOutcome,
    reason: Option<DeliveryReason>,
    receipt_for: MessageId,
    at: Timestamp,
) -> String {
    let what = match outcome {
        ReceiptOutcome::Delivered => "was popped by the recipient",
        ReceiptOutcome::Delayed => "has not been popped yet and is still queued",
        ReceiptOutcome::Expired => "expired before anyone popped it",
        ReceiptOutcome::WakeFailed => "could not wake the recipient",
        ReceiptOutcome::AgentUnavailable => "found the recipient unavailable",
        ReceiptOutcome::QuotaExhausted => "found the recipient out of quota",
        ReceiptOutcome::Dead => "was given up after repeated delivery attempts",
    };
    let reason = reason.map_or("none", DeliveryReason::as_str);
    format!(
        "ai-memory delivery receipt. Message {receipt_for} {what}. \
         Outcome: {outcome}. Reason: {reason}. At: {at}. \
         The sending coordinate of this receipt is the recipient project. \
         Read the full status with memory_message_list (box \"outbox\", message_id \
         \"{receipt_for}\", include_settled true). This receipt contains no text \
         from the recipient.",
        outcome = outcome.as_str(),
    )
}

