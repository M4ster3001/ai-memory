    #[test]
    fn notify_accepts_only_well_formed_lists() {
        use NotifyClass::*;
        assert_eq!(NotifyOn::from_classes(&[Never]).unwrap(), NotifyOn::NEVER);
        assert_eq!(
            NotifyOn::from_classes(&[Delay, Failure]).unwrap(),
            NotifyOn::DEFAULT
        );
        assert!(NotifyOn::from_classes(&[]).is_err());
        assert!(NotifyOn::from_classes(&[Never, Success]).is_err());
        assert!(NotifyOn::from_classes(&[Failure, Failure]).is_err());
        assert_eq!(NotifyOn::DEFAULT.as_canonical(), "failure,delay");
        assert_eq!(NotifyOn::NEVER.as_canonical(), "never");
    }

    #[test]
    fn notify_storage_form_round_trips_and_rejects_anything_else() {
        let all = [
            NotifyClass::Failure,
            NotifyClass::Delay,
            NotifyClass::Success,
        ];
        for mask in 0..8u8 {
            let classes: Vec<_> = all
                .iter()
                .enumerate()
                .filter(|(i, _)| mask & (1 << i) != 0)
                .map(|(_, c)| *c)
                .collect();
            let notify = if classes.is_empty() {
                NotifyOn::NEVER
            } else {
                NotifyOn::from_classes(&classes).unwrap()
            };
            let stored = notify.as_canonical();
            assert_eq!(NotifyOn::from_str(&stored).unwrap(), notify, "{stored}");
        }
        for bad in [
            "",
            "delay,failure",
            "never,failure",
            "failure,",
            "FAILURE",
            "all",
        ] {
            assert!(NotifyOn::from_str(bad).is_err(), "{bad:?}");
        }
    }

    #[test]
    fn requested_ttl_shortens_and_never_extends() {
        let policy = DeliveryPolicy::default();
        let now = 1_000_000_000_000;
        let d = policy.deadlines(MessagePriority::High, None, now);
        assert_eq!(d.expires_at_us, now + 24 * 3600 * 1_000_000);
        assert_eq!(d.no_pop_alert_at_us, Some(now + 15 * 60 * 1_000_000));
        let short = policy.deadlines(MessagePriority::High, Some(600), now);
        assert_eq!(short.expires_at_us, now + 600 * 1_000_000);
        // The alert would fire after expiry, so it is dropped.
        assert_eq!(short.no_pop_alert_at_us, None);
        let long = policy.deadlines(MessagePriority::High, Some(MAX_MESSAGE_TTL_SECS), now);
        assert_eq!(long.expires_at_us, d.expires_at_us);
        let low = policy.deadlines(MessagePriority::Low, None, now);
        assert_eq!(low.no_pop_alert_at_us, None);
    }

    #[test]
    fn deadlines_saturate_instead_of_wrapping() {
        let policy = DeliveryPolicy {
            ttl_low_secs: u64::MAX,
            ttl_normal_secs: u64::MAX,
            ttl_high_secs: u64::MAX,
            alert_normal_secs: Some(u64::MAX),
            alert_high_secs: None,
        };
        let d = policy.deadlines(MessagePriority::Normal, None, i64::MAX - 5);
        assert_eq!(d.expires_at_us, i64::MAX);
        assert_eq!(d.no_pop_alert_at_us, None);
    }

    #[test]
    fn receipt_text_is_built_from_ids_and_enums_only() {
        let id = MessageId::new();
        let at = Timestamp::from_second(1_800_000_000).unwrap();
        for outcome in ReceiptOutcome::ALL {
            for reason in std::iter::once(None).chain(DeliveryReason::ALL.iter().copied().map(Some))
            {
                let subject = receipt_subject(*outcome, id);
                let body = receipt_body(*outcome, reason, id, at);
                assert!(subject.starts_with("receipt: "));
                assert!(!subject.contains('\n') && !body.contains('\n'));
                assert!(body.contains(&id.to_string()));
                assert!(body.contains(outcome.as_str()));
                assert!(body.chars().all(|c| c.is_ascii() && !c.is_ascii_control()));
            }
        }
    }

    #[test]
    fn each_outcome_maps_to_the_notify_keyword_that_requests_it() {
        assert_eq!(
            ReceiptOutcome::Delivered.notify_class(),
            NotifyClass::Success
        );
        assert_eq!(ReceiptOutcome::Delayed.notify_class(), NotifyClass::Delay);
        assert_eq!(ReceiptOutcome::Expired.notify_class(), NotifyClass::Failure);
        assert!(!NotifyOn::NEVER.wants(ReceiptOutcome::Expired.notify_class()));
        assert!(NotifyOn::DEFAULT.wants(ReceiptOutcome::Delayed.notify_class()));
        assert!(!NotifyOn::DEFAULT.wants(ReceiptOutcome::Delivered.notify_class()));
    }
