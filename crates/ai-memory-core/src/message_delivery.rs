//! Delivery state, deadlines and receipts for cross-project agent messages.
//!
//! A message has two states. The queue state ([`crate::MessageState`]) is what
//! the claim guards read. The delivery state ([`DeliveryState`]) tells the
//! sender what happened to it, with a [`DeliveryReason`] that is always an
//! enumerated value. Time-based transitions (expiry, the "not popped yet"
//! alert) are applied by a bounded server sweep, and the sender can ask for a
//! receipt: a server-generated message in its own inbox, modelled on SMTP
//! delivery status notifications (RFC 3461, RFC 5321 §3.6.3).
//!
//! A receipt carries ids, enumerated values and timestamps only. Nothing the
//! recipient wrote reaches it, and a receipt never produces another receipt.
//! See `docs/agent-messaging.md` and
//! `docs/design-agent-wakeup-and-secure-messaging.md`.

use jiff::Timestamp;
use serde::{Deserialize, Serialize};

use crate::ids::MessageId;

/// Declares a closed, string-backed enumeration with its wire spelling.
macro_rules! wire_enum {
    (
        $(#[$meta:meta])*
        $name:ident, $what:literal {
            $( $(#[$vmeta:meta])* $variant:ident => $wire:literal ),+ $(,)?
        }
    ) => {
        $(#[$meta])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, schemars::JsonSchema)]
        #[serde(rename_all = "snake_case")]
        pub enum $name {
            $( $(#[$vmeta])* $variant ),+
        }

        impl $name {
            /// Every value, in declaration order.
            pub const ALL: &'static [Self] = &[$(Self::$variant),+];

            /// Canonical wire and storage string.
            #[must_use]
            pub const fn as_str(self) -> &'static str {
                match self {
                    $(Self::$variant => $wire),+
                }
            }
        }

        impl std::str::FromStr for $name {
            type Err = crate::MemoryError;

            fn from_str(s: &str) -> Result<Self, Self::Err> {
                match s {
                    $($wire => Ok(Self::$variant),)+
                    other => Err(crate::MemoryError::MalformedRecord(format!(
                        concat!("unknown ", $what, ": {}"),
                        other
                    ))),
                }
            }
        }
    };
}

wire_enum! {
    /// How urgent a message is. It picks the default time to live and the
    /// "not popped yet" alert (see [`DeliveryPolicy`]).
    #[derive(Default)]
    MessagePriority, "message priority" {
        /// Long time to live, no alert.
        Low => "low",
        /// The default.
        #[default]
        Normal => "normal",
        /// Short time to live, early alert.
        High => "high",
    }
}

wire_enum! {
    /// What a row in `agent_messages` is.
    MessageKind, "message kind" {
        /// Composed by an agent or an operator.
        Message => "message",
        /// Generated by the server to tell a sender what happened to a
        /// message. Fixed structure, no recipient text.
        Receipt => "receipt",
    }
}

wire_enum! {
    /// What happened to a message, as the sender sees it. Separate from the
    /// queue state that the claim guards read.
    ///
    /// The server sets `queued`, `awaiting_agent`, `delivered`, `expired` and
    /// `cancelled` itself. `wake_attempted`, `wake_failed`, `agent_unavailable`
    /// and `quota_exhausted` come from the host wake supervisor's reports
    /// (`POST /inbox/wake-report`, [`crate::message_wake::WakeOutcome`]).
    /// `dead` belongs to delivery leases, a later stage of the design, and
    /// nothing sets it yet; it is part of the stored vocabulary so a reader
    /// never fails on it.
    DeliveryState, "delivery state" {
        /// Stored and claimable; no wake attempted.
        Queued => "queued",
        /// Addressed to a harness that has never been seen in the recipient
        /// project. It becomes `queued` when that harness first starts a
        /// session there.
        AwaitingAgent => "awaiting_agent",
        /// The wake supervisor launched a wake that its adapter accepted.
        WakeAttempted => "wake_attempted",
        /// Popped by the recipient. Terminal.
        Delivered => "delivered",
        /// A wake failed or was not launched; the reason says why.
        WakeFailed => "wake_failed",
        /// The wake adapter could not run at all.
        AgentUnavailable => "agent_unavailable",
        /// The recipient's harness reported exhausted quota.
        QuotaExhausted => "quota_exhausted",
        /// The time to live passed while it waited. Terminal.
        Expired => "expired",
        /// Reserved: redeliveries exhausted. Terminal.
        Dead => "dead",
        /// The sender retracted it. Terminal.
        Cancelled => "cancelled",
    }
}

wire_enum! {
    /// Why a message is in its delivery state. Never free text.
    ///
    /// The server records `agent_not_registered`, `no_pop_timeout`, `ttl` and
    /// `sender_cancelled` itself. The wake supervisor reports the adapter,
    /// approval, session and loop reasons. `budget_exhausted` is no longer
    /// produced (wakes have no hourly budget) and stays readable on old rows;
    /// `rate_limited` and `sender_unverified` are not produced yet.
    DeliveryReason, "delivery reason" {
        /// Addressed to a harness not registered in the recipient project.
        AgentNotRegistered => "agent_not_registered",
        /// Nobody popped it within the priority's alert window.
        NoPopTimeout => "no_pop_timeout",
        /// Its time to live passed.
        Ttl => "ttl",
        /// The sender cancelled it.
        SenderCancelled => "sender_cancelled",
        /// The wake adapter exited with an error or was killed by a signal.
        AdapterExitNonzero => "adapter_exit_nonzero",
        /// The wake adapter ran past its timeout and was stopped.
        AdapterTimeout => "adapter_timeout",
        /// The wake adapter's program could not be started.
        BinaryMissing => "binary_missing",
        /// The wake adapter has no valid operator approval.
        NotApproved => "not_approved",
        /// The recipient's hourly wake budget was spent. Older supervisors
        /// only.
        BudgetExhausted => "budget_exhausted",
        /// The recipient's session refused the wake as busy, or is open in
        /// a process the adapter must not resume.
        SessionBusy => "session_busy",
        /// The harness has no session with the recorded handle.
        SessionNotFound => "session_not_found",
        /// [`crate::quota::quota_signal`] matched the wake adapter's output.
        QuotaMarker => "quota_marker",
        /// Reserved.
        RateLimited => "rate_limited",
        /// The harness refused its own login for this kind of run.
        AuthFailed => "auth_failed",
        /// Reserved.
        SenderUnverified => "sender_unverified",
        /// The sender and recipient look like agents waking each other in a
        /// loop, so wakes between them are paused until a human prompt or
        /// the dashboard resumes them. The mail itself is still delivered.
        LoopSuspected => "loop_suspected",
    }
}

